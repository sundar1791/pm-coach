#!/usr/bin/env node
/**
 * Reads the most recent briefing from briefings/ and emails it via Resend.
 * No Claude API involved — run this after Claude Code commits a new briefing.
 *
 * Required env var: RESEND_API_KEY
 */

import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const RECIPIENT_EMAIL = 'sundar1791@gmail.com';
const FROM_EMAIL      = 'AGI Briefing <onboarding@resend.dev>';

const { RESEND_API_KEY } = process.env;
if (!RESEND_API_KEY) throw new Error('Missing RESEND_API_KEY');

// ── Find the latest briefing file ─────────────────────────────────────────────

const dir   = 'briefings';
const files = readdirSync(dir)
  .filter(f => f.startsWith('agi-briefing-') && f.endsWith('.md'))
  .sort(); // YYYY-MM-DD names sort chronologically

if (!files.length) throw new Error(`No briefing files found in ${dir}/`);

const latest = files.at(-1);
const mdPath = join(dir, latest);
const date   = latest.replace('agi-briefing-', '').replace('.md', '');

console.log(`Sending briefing: ${mdPath}`);

const briefingMd = readFileSync(mdPath, 'utf8').trim();

// ── Markdown → HTML ───────────────────────────────────────────────────────────

function mdToHtml(md) {
  const out   = [];
  let inPara  = false;

  const flush  = () => { if (inPara) { out.push('</p>'); inPara = false; } };
  const inline = s => s
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/\*(.+?)\*/g,     '<em>$1</em>')
    .replace(/`(.+?)`/g,       '<code style="background:#f4f4f4;padding:1px 4px;border-radius:3px">$1</code>')
    .replace(/\[(.+?)\]\((.+?)\)/g, '<a href="$2" style="color:#0f3460">$1</a>');

  for (const raw of md.split('\n')) {
    const line = raw.trimEnd();
    if (!line)                 { flush(); continue; }
    if (/^# (.+)/.test(line))  { flush(); out.push(`<h1 style="font-size:1.55em;border-bottom:2px solid #1a1a2e;padding-bottom:8px;color:#1a1a2e;margin-top:0">${inline(line.slice(2))}</h1>`); continue; }
    if (/^## (.+)/.test(line)) { flush(); out.push(`<h2 style="font-size:1.15em;color:#16213e;margin-top:2em;border-bottom:1px solid #eee;padding-bottom:3px">${inline(line.slice(3))}</h2>`); continue; }
    if (/^### (.+)/.test(line)){ flush(); out.push(`<h3 style="font-size:1em;color:#0f3460;margin-top:1.4em">${inline(line.slice(4))}</h3>`); continue; }
    if (/^---+$/.test(line))   { flush(); out.push('<hr style="border:none;border-top:1px solid #ddd;margin:1.6em 0">'); continue; }
    if (!inPara) { out.push('<p style="margin:.5em 0;line-height:1.75">'); inPara = true; } else out.push('<br>');
    out.push(inline(line));
  }
  flush();
  return out.join('\n');
}

const html = `<!DOCTYPE html>
<html lang="en">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head>
<body style="font-family:Georgia,serif;max-width:680px;margin:32px auto;color:#222;padding:0 20px">
${mdToHtml(briefingMd)}
<p style="font-size:.8em;color:#aaa;margin-top:3em;border-top:1px solid #eee;padding-top:1em">
  AGI Daily Briefing &middot; generated by Claude Code &middot;
  <a href="https://github.com/sundar1791/pm-coach/tree/daily-ai-updates/briefings" style="color:#aaa">archive</a>
</p>
</body></html>`;

// ── Send via Resend ───────────────────────────────────────────────────────────

const res = await fetch('https://api.resend.com/emails', {
  method:  'POST',
  headers: { Authorization: `Bearer ${RESEND_API_KEY}`, 'Content-Type': 'application/json' },
  body: JSON.stringify({
    from:    FROM_EMAIL,
    to:      [RECIPIENT_EMAIL],
    subject: `AGI Briefing — ${date}`,
    html,
    text: briefingMd,
  }),
});

if (!res.ok) throw new Error(`Resend ${res.status}: ${await res.text()}`);

const { id } = await res.json();
console.log(`Email sent ✓  (id: ${id})`);
